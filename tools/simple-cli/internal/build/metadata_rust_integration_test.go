// A RUST ACTION IS DESCRIBED BY THE SAME GENERATOR AS EVERY OTHER ACTION, AND
// THESE RUN IT.
//
// It was not, and the way it failed is the reason these are integration tests
// rather than unit tests. Nothing in this package refused a Rust action: it was
// simply not recognised as an action in any language, so the description, the
// input schema and the statement about whether an agent may call it were never
// asked for. The module compiled, the build reported success, and the file
// beside it that says what the action is was never written.
//
// So what is exercised here is the whole path — the language read off the
// directory, the generator unpacked with its companions beside it, the crate
// compiled, and the answer written to disk — because every one of those was a
// place the action could go missing without anything failing.
func writeRustAction(t *testing.T, name, source string) string {
	t.Helper()

	actionDir := filepath.Join(t.TempDir(), name)
	if err := os.MkdirAll(filepath.Join(actionDir, "src"), 0755); err != nil {
		t.Fatalf("failed to create the action directory: %v", err)
	}

	if err := os.WriteFile(filepath.Join(actionDir, "src", "main.rs"), []byte(source), 0644); err != nil {
		t.Fatalf("failed to write the action source: %v", err)
	}

	manifest := "[package]\nname = \"" + name + "\"\nversion = \"0.1.0\"\nedition = \"2021\"\n"
	if err := os.WriteFile(filepath.Join(actionDir, "Cargo.toml"), []byte(manifest), 0644); err != nil {
		t.Fatalf("failed to write the action manifest: %v", err)
	}

	return actionDir
}

// requireRustGenerator skips where the generator cannot run at all.
//
// Cargo as well as node, because the Rust half of the generator is a crate: it
// has to be compiled before it can be asked anything, and a machine without a
// Rust toolchain is a machine that cannot describe a Rust action. That is the
// same requirement building one already has.
func requireRustGenerator(t *testing.T) {
	t.Helper()

	requireGenerator(t)

	if _, err := EnsureCargo(); err != nil {
		t.Skip("cargo not available, skipping integration test")
	}
}

const rustPayloadSource = `
/// What the caller sends this action.
#[derive(Deserialize, Schema)]
struct Input {
    /// Who to greet.
    name: String,
}
`

// THE ACTION THAT USED TO GO MISSING.
//
// A Rust action reaching this path answered with the language it could not
// detect, and an action with no action.json is an action no agent can be offered
// and no reader can check: the description, the schema and the exposure
// statement are all in the file that was never written.
func TestRustActionIsDescribed(t *testing.T) {
	requireRustGenerator(t)

	actionDir := writeRustAction(t, "greet-user", `use simpleplatform_sdk::prelude::*;
`+rustPayloadSource+`
/// Greets whoever the caller names.
///
/// @tool
/// @shortdesc Greet whoever the caller names, and answer with the greeting.
/// @usewhen A greeting is wanted for a named person.
/// @Payload Input
fn handler(request: Request<Input>) -> Result<Output, Error> {
    Ok(Output {})
}
`)

	if err := ExtractMetadata(fsx.OSFileSystem{}, actionDir); err != nil {
		t.Fatalf("expected the action to be described, got %v", err)
	}

	metadata := generatedActionMetadata(t, actionDir)

	if metadata.description() == "" {
		t.Fatal("the action was described by nothing at all")
	}

	if metadata.value("ai", "tool") != true {
		t.Fatalf("the exposure statement did not reach the artifact: %#v", metadata.object("ai"))
	}

	if metadata.value("ai", "shortdesc") != "Greet whoever the caller names, and answer with the greeting." {
		t.Fatalf("the listing line did not reach the artifact: %#v", metadata.object("ai"))
	}

	if metadata.object("schema", "properties", "name") == nil {
		t.Fatalf("the payload the action names was not read: %#v", metadata.value("schema"))
	}
}

// THE MEMBER ORDER AND THE BYTES ARE THE GENERATOR'S.
//
// The file this tool leaves behind has to be the file the platform's own build
// writes from the same source, down to the byte: a contract regenerated by two
// tools that disagree about key order is a contract that shows up as a diff
// every time the other tool touches it.
func TestRustActionLeavesTheGeneratorsBytesAlone(t *testing.T) {
	requireRustGenerator(t)

	actionDir := writeRustAction(t, "greet-user", `use simpleplatform_sdk::prelude::*;
`+rustPayloadSource+`
/// Greets whoever the caller names.
///
/// @tool
/// @shortdesc Greet whoever the caller names.
fn handler(request: Request<Input>) -> Result<Output, Error> {
    Ok(Output {})
}
`)

	if err := ExtractMetadata(fsx.OSFileSystem{}, actionDir); err != nil {
		t.Fatalf("expected the action to be described, got %v", err)
	}

	written, err := os.ReadFile(filepath.Join(actionDir, "action.json"))
	if err != nil {
		t.Fatalf("failed to read action.json: %v", err)
	}

	// An action that writes no `@usewhen` states none, rather than stating an
	// empty list a reader then has to tell apart from an unstated one.
	if strings.Contains(string(written), "usewhen") {
		t.Fatalf("an unwritten @usewhen was stated as empty:\n%s", written)
	}

	if err := ExtractMetadata(fsx.OSFileSystem{}, actionDir); err != nil {
		t.Fatalf("second extraction failed: %v", err)
	}

	again, err := os.ReadFile(filepath.Join(actionDir, "action.json"))
	if err != nil {
		t.Fatalf("failed to read action.json: %v", err)
	}

	if string(again) != string(written) {
		t.Fatalf("the generated contract is not stable across runs:\n%s\n---\n%s", written, again)
	}
}

// THE SAME TWO PROPERTIES THE OTHER TWO LANGUAGES ARE HELD TO.
//
// The exposure statement is read from EVERY comment in the file, so writing it
// somewhere other than the comment that supplies the description does not
// quietly leave the action uncallable. And the claimed names are lifted out of
// the description line by line, so an author may state their tags and keep
// writing — what follows is part of what the tool says it does, and reading the
// description as the text before the first tag would delete it.
//
// A name the vocabulary does not claim is left exactly where its author put it.
// It is not this generator's word, and a line lifted out on the strength of its
// leading `@` is a sentence deleted from what a model reads.
func TestRustActionKeepsWhatIsWrittenAroundTheAnnotations(t *testing.T) {
	requireRustGenerator(t)

	actionDir := writeRustAction(t, "query-things", `//! The things module.
//!
//! @tool
//! @shortdesc Reads things by name.

use simpleplatform_sdk::prelude::*;

/// Reads things.
///
/// @usewhen A caller names one thing and wants the row behind it.
/// @todo Answer with the rows around it too.
///
/// A name matching no row is REFUSED rather than answered with an empty
/// result, so an empty answer is never false good news.
#[derive(Deserialize, Schema)]
struct Payload {
    /// The thing to read.
    name: String,
}

fn handler(request: Request<Payload>) -> Result<Output, Error> {
    Ok(Output {})
}
`)

	if err := ExtractMetadata(fsx.OSFileSystem{}, actionDir); err != nil {
		t.Fatalf("expected the action to be described, got %v", err)
	}

	metadata := generatedActionMetadata(t, actionDir)

	if metadata.value("ai", "tool") != true {
		t.Fatalf("an exposure statement written outside the describing comment was dropped: %#v", metadata.object("ai"))
	}

	if !strings.Contains(metadata.description(), "REFUSED rather than answered") {
		t.Fatalf("the description lost the rule written after the annotations, got %q", metadata.description())
	}

	for _, claimed := range []string{"@tool", "@shortdesc", "@usewhen"} {
		if strings.Contains(metadata.description(), claimed) {
			t.Fatalf("%s was left in the description, got %q", claimed, metadata.description())
		}
	}

	if !strings.Contains(metadata.description(), "@todo") {
		t.Fatalf("a name the vocabulary does not claim was taken out of the author's prose, got %q", metadata.description())
	}
}

// A MALFORMED STATEMENT REFUSES, AND THE REFUSAL REACHES THE AUTHOR WHOLE.
//
// The generator runs in a child process and the crate it asks about Rust runs in
// another one below that, so the sentence has two boundaries to survive. What an
// author gets told is the only thing that makes the failure actionable: the
// action, the tag, and what would have been accepted instead.
func TestRustActionRefusesAMalformedExposureStatement(t *testing.T) {
	requireRustGenerator(t)

	cases := []struct {
		name      string
		statement string
		want      []string
	}{
		{
			name:      "a qualifier without the modifier it qualifies",
			statement: "/// @shortdesc Reads things by name.",
			want:      []string{"query-things", "@shortdesc", "@tool", "says nothing"},
		},
		{
			name:      "a value written after the modifier tag",
			statement: "/// @tool true\n/// @shortdesc Reads things by name.",
			want:      []string{"query-things", "modifier tag and takes no value", `"true"`},
		},
		{
			name:      "a tool with no line for the listing to carry",
			statement: "/// @tool",
			want:      []string{"query-things", "must declare @shortdesc"},
		},
		{
			name:      "a name one edit from a claimed one",
			statement: "/// @tool\n/// @shortdes Reads things by name.",
			want:      []string{"query-things", "@shortdes", "one edit from @shortdesc"},
		},
		{
			name:      "a listing line longer than a listing carries",
			statement: "/// @tool\n/// @shortdesc Reads things by name.\n/// @usewhen " + strings.Repeat("x", 101),
			want:      []string{"query-things", "101 characters", "at most 100"},
		},
	}

	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			actionDir := writeRustAction(t, "query-things", `use simpleplatform_sdk::prelude::*;
`+rustPayloadSource+`
/// Reads things.
///
`+testCase.statement+`
/// @Payload Input
fn handler(request: Request<Input>) -> Result<Output, Error> {
    Ok(Output {})
}
`)

			err := ExtractMetadata(fsx.OSFileSystem{}, actionDir)
			if err == nil {
				t.Fatal("expected a refusal")
			}

			for _, want := range testCase.want {
				if !strings.Contains(err.Error(), want) {
					t.Fatalf("expected the refusal to mention %q, got %q", want, err.Error())
				}
			}
		})
	}
}

// A REFUSED SOURCE TAKES ITS STALE OUTPUT WITH IT, AND A TOOLCHAIN THAT COULD
// NOT RUN DOES NOT.
//
// The two failures are told apart by an exit status and by nothing else, and the
// difference decides what the file on disk is worth. A refused source has made
// the action.json beside it describe an action that no longer exists, so leaving
// it is how a rejected edit ships. A companion that could not be compiled has
// said nothing about whether that file is true, and discarding every action's
// metadata because a toolchain is absent turns one environment problem into a
// tree nobody can build from.
func TestARefusedRustSourceDiscardsTheActionJSONItHasMadeUntrue(t *testing.T) {
	requireRustGenerator(t)

	actionDir := writeRustAction(t, "query-things", `use simpleplatform_sdk::prelude::*;
`+rustPayloadSource+`
/// Reads things.
///
/// @tool sometimes
/// @shortdesc Reads things by name.
/// @Payload Input
fn handler(request: Request<Input>) -> Result<Output, Error> {
    Ok(Output {})
}
`)

	stalePath := filepath.Join(actionDir, "action.json")
	if err := os.WriteFile(stalePath, []byte(`{"description":"Reads things.","ai":{"tool":true}}`), 0644); err != nil {
		t.Fatalf("failed to write the stale metadata: %v", err)
	}

	if err := ExtractMetadata(fsx.OSFileSystem{}, actionDir); err == nil {
		t.Fatal("expected a refusal")
	}

	if _, err := os.Stat(stalePath); err == nil {
		t.Fatal("the refused source left its earlier description shipping")
	}
}

func TestARustCompanionThatCouldNotBeBuiltLeavesTheActionJSONAlone(t *testing.T) {
	requireRustGenerator(t)

	actionDir := writeRustAction(t, "query-things", `use simpleplatform_sdk::prelude::*;
`+rustPayloadSource+`
/// Reads things.
///
/// @tool
/// @shortdesc Reads things by name.
/// @Payload Input
fn handler(request: Request<Input>) -> Result<Output, Error> {
    Ok(Output {})
}
`)

	if err := ExtractMetadata(fsx.OSFileSystem{}, actionDir); err != nil {
		t.Fatalf("expected the action to be described, got %v", err)
	}

	described, err := os.ReadFile(filepath.Join(actionDir, "action.json"))
	if err != nil {
		t.Fatalf("failed to read action.json: %v", err)
	}

	t.Setenv("PATH", brokenCargoToolchain(t)+string(os.PathListSeparator)+os.Getenv("PATH"))

	if err := ExtractMetadata(fsx.OSFileSystem{}, actionDir); err == nil {
		t.Fatal("expected the extraction to fail")
	}

	kept, err := os.ReadFile(filepath.Join(actionDir, "action.json"))
	if err != nil {
		t.Fatalf("a companion that could not be built took the action's description with it: %v", err)
	}

	if string(kept) != string(described) {
		t.Fatalf("a companion that could not be built rewrote the action's description:\n%s\n---\n%s", kept, described)
	}
}

// brokenCargoToolchain is a directory holding a `cargo` that fails for a reason
// that is not a refusal.
//
// It is a cargo that is THERE and does not work, rather than a PATH with no
// cargo on it, because those are two different failures and only one of them is
// about the companion: a machine with no Rust toolchain is told to install one
// before either extraction or compilation is attempted.
func brokenCargoToolchain(t *testing.T) string {
	t.Helper()

	dir := t.TempDir()

	shim := filepath.Join(dir, "cargo")
	if err := os.WriteFile(shim, []byte("#!/bin/sh\necho 'cargo: cannot find the toolchain' >&2\nexit 1\n"), 0755); err != nil {
		t.Fatalf("failed to write the shim: %v", err)
	}

	return dir
}
